defmodule Tickmark.Testing.Holidays do
  @moduledoc """
  2025년 한국 공휴일표 (도메인 문서 2.10).

  `weekend_holiday_posting` 룰과 합성 GL 생성기(`Tickmark.Ledger.Generator`)가 함께 쓴다.
  표는 코드 상수이고, engagement 별로 더할 휴일은 룰 파라미터 `extra_holidays` 로 넣는다
  (설계 문서 2.2).

  - 합계 19일. 주말과 겹치는 공휴일(03-01 토 삼일절, 10-05 일 추석 연휴)도 표에 그대로 둔다.
  - 5월 1일 근로자의 날은 넣지 않는다. 법정 공휴일 여부는 도메인 문서에서 "확인 필요"다.
  - 2025-12-29 ~ 12-31 은 평일이며 휴일이 아니다.
  - 2025년 이외의 연도는 표가 없어서 `holiday?/1` 이 false 를 돌려준다.
    "휴일표 없음" 경고는 룰이 남긴다.
  """

  # 도메인 문서 2.10 표 그대로. 명칭은 읽는 사람을 위한 것이고 판정에는 날짜만 쓴다.
  @holidays_2025 [
    {~D[2025-01-01], "신정"},
    {~D[2025-01-27], "임시공휴일"},
    {~D[2025-01-28], "설날 연휴"},
    {~D[2025-01-29], "설날"},
    {~D[2025-01-30], "설날 연휴"},
    {~D[2025-03-01], "삼일절"},
    {~D[2025-03-03], "삼일절 대체공휴일"},
    {~D[2025-05-05], "어린이날, 부처님오신날"},
    {~D[2025-05-06], "대체공휴일"},
    {~D[2025-06-03], "제21대 대통령선거일"},
    {~D[2025-06-06], "현충일"},
    {~D[2025-08-15], "광복절"},
    {~D[2025-10-03], "개천절"},
    {~D[2025-10-05], "추석 연휴"},
    {~D[2025-10-06], "추석"},
    {~D[2025-10-07], "추석 연휴"},
    {~D[2025-10-08], "추석 대체공휴일"},
    {~D[2025-10-09], "한글날"},
    {~D[2025-12-25], "성탄절"}
  ]

  @dates @holidays_2025 |> Enum.map(&elem(&1, 0)) |> Enum.sort(Date)

  @doc "휴일표의 모든 날짜를 오름차순으로 돌려준다."
  @spec all() :: [Date.t()]
  def all, do: @dates

  @doc "날짜가 휴일표에 있으면 true. 주말 여부는 보지 않는다."
  @spec holiday?(Date.t()) :: boolean()
  def holiday?(%Date{} = date), do: date in @dates
end
